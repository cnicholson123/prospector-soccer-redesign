import { afterEach, expect, it } from 'vitest';
import { rm } from 'node:fs/promises';
import { adminFixture } from '../helpers/admin.js';
import { createAdminApp } from '../../server/http/hono-app.js';
import { createRenderHandler } from '../../server/render/handler.js';
import { newSession, DAY } from '../../server/auth/session.js';
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });
async function fixture(seed = false) { const f = await adminFixture(seed); roots.push(f.root); await f.login(); return f; }
it('one-time account credentials, ceilings, active state and revocation remain audited and secret-free', async () => {
  const f = await fixture();
  const created = await f.req('/users', 'POST', { username: 'Writer', displayName: 'Club writer', role: 'Contributor' });
  expect(created.status).toBe(201);
  const { user, temporaryPassword } = await created.json();
  expect(temporaryPassword.length).toBeGreaterThanOrEqual(18); expect(user).not.toHaveProperty('passwordHash');
  const writer = await f.login('Writer', temporaryPassword); expect(writer.response.status).toBe(200); expect(writer.data.user.mustChangePassword).not.toBe(true);
  expect((await f.req('/publish', 'POST', {})).status).toBe(403);
  expect((await f.req('/users')).status).toBe(403);
  await f.login();
  expect((await f.req(`/users/${user.id}`, 'PATCH', { role: 'Editor' })).status).toBe(200);
  expect((await f.app.request('/api/admin/auth/me', { headers: { Cookie: writer.response.headers.get('set-cookie')!.split(';')[0] } })).status).toBe(401);
  const reset = await (await f.req(`/users/${user.id}/reset-password`, 'POST')).json();
  expect(reset.temporaryPassword).not.toBe(temporaryPassword);
  expect((await f.login('Writer', reset.temporaryPassword)).response.status).toBe(200);
  await f.login();
  expect((await f.req(`/users/${user.id}`, 'DELETE')).status).toBe(200);
  expect((await f.login('Writer', reset.temporaryPassword)).response.status).toBe(401);
  await f.login();
  expect((await f.req(`/users/${user.id}`, 'PATCH', { active: true })).status).toBe(200);
  expect((await f.login('Writer', reset.temporaryPassword)).response.status).toBe(200);
  await f.login();
  expect((await f.req(`/users/${user.id}/revoke-sessions`, 'POST')).status).toBe(200);
  const users = await (await f.req('/users')).json(); expect(JSON.stringify(users)).not.toMatch(/passwordHash|temporaryPassword|scrypt\$/);
  const admin = await (await f.req('/users', 'POST', { username: 'AdminUser', role: 'Admin' })).json();
  await f.login('AdminUser', admin.temporaryPassword);
  expect((await f.req('/users', 'POST', { username: 'ForbiddenOwner', role: 'Owner' })).status).toBe(403);
  const owner = users.users.find((u: { role: string }) => u.role === 'Owner');
  expect((await f.req(`/users/${owner.id}/reset-password`, 'POST')).status).toBe(403);
  expect((await f.req(`/users/${owner.id}`, 'PATCH', { role: 'Viewer' })).status).toBe(403);
  const audit = JSON.stringify((await f.store.queryAudit({ limit: 100 })).items);
  for (const name of ['users.create','users.update','users.deactivate','users.reset_password','users.revoke_sessions']) expect(audit).toContain(name);
  for (const secret of [temporaryPassword, reset.temporaryPassword, admin.temporaryPassword, 'scrypt$']) expect(audit).not.toContain(secret);
});
it('Contributor requests, Editor returns with required note and approves a fresh version to the public page', async () => {
  const f = await fixture(true);
  const writer = await (await f.req('/users', 'POST', { username: 'ReviewerWriter', role: 'Contributor' })).json();
  await f.login('ReviewerWriter', writer.temporaryPassword);
  const { doc } = await (await f.req('/docs/events', 'POST', { draft: { title: 'Phase eleven community event', date: '2030-06-01', showOnHome: true } })).json();
  const request = await (await f.req(`/docs/events/${doc.id}/review`, 'POST', { baseVersion: doc.version, note: 'Please check' })).json();
  expect((await f.req(`/docs/events/${doc.id}/review`, 'DELETE', { baseVersion: request.doc.version, note: 'Cannot self-return' })).status).toBe(403);
  expect((await f.req('/reviews')).status).toBe(403);
  await f.login();
  expect((await (await f.req('/reviews')).json()).docs.map((d: {id:string}) => d.id)).toContain(doc.id);
  expect((await f.req(`/docs/events/${doc.id}/review`, 'DELETE', { baseVersion: request.doc.version, note: '  ' })).status).toBe(422);
  const returned = await (await f.req(`/docs/events/${doc.id}/review`, 'DELETE', { baseVersion: request.doc.version, note: 'Please confirm the location.' })).json();
  expect(returned.doc.reviewRequestedBy).toBeUndefined();
  await f.login('ReviewerWriter', writer.temporaryPassword);
  expect((await (await f.req(`/docs/events/${doc.id}`)).json()).doc.reviewNote).toBe('Please confirm the location.');
  const edited = await (await f.req(`/docs/events/${doc.id}`, 'PUT', { baseVersion: returned.doc.version, draft: { ...doc.draft, location: 'Club fields' } })).json();
  const resubmitted = await (await f.req(`/docs/events/${doc.id}/review`, 'POST', { baseVersion: edited.doc.version })).json();
  await f.login();
  expect((await f.req('/publish', 'POST', { items: [{ collection: 'events', id: doc.id, expectedVersion: request.doc.version }] })).status).toBe(409);
  expect((await f.req('/publish', 'POST', { items: [{ collection: 'events', id: doc.id, expectedVersion: resubmitted.doc.version }] })).status).toBe(200);
  const published = (await (await f.req(`/docs/events/${doc.id}`)).json()).doc;
  expect(published.reviewNote).toBeUndefined(); expect(published.reviewRequestedBy).toBeUndefined();
  const render = createRenderHandler(f.store, f.config, () => new Date('2030-01-01'));
  expect(await (await render(new Request('http://localhost:3000/'))).text()).toContain(doc.draft.title);
  const audit = (await f.store.queryAudit({ action: 'content.review_return', limit: 10 })).items;
  expect(audit[0].meta?.summary).toBe('Please confirm the location.');
});
it('lists only active, same-generation own sessions; password rotation and current revocation work', async () => {
  const f = await fixture(), user = (await f.store.listUsers())[0], now = new Date('2030-01-01T12:00:00Z');
  await newSession(f.store, user, {}, new Date(now.getTime() - 31 * DAY));
  const stale = await newSession(f.store, { ...user, authVersion: 5 }, {}, now);
  const other = await newSession(f.store, user, {}, now);
  const list = await (await f.req('/auth/sessions')).json();
  expect(list.sessions).toHaveLength(2); expect(list.sessions.some((s: {hash:string}) => s.hash === stale.session.hash)).toBe(false);
  expect(JSON.stringify(list)).not.toContain('csrfToken');
  expect((await f.req('/auth/sessions/revoke-others', 'POST')).status).toBe(200);
  expect(await f.store.getSession(other.session.hash)).toBeNull();
  const changed = await f.req('/auth/password', 'POST', { current: 'Phil', next: 'A uniquely long testing passphrase' });
  expect(changed.status).toBe(200);
  const auth = await changed.json(); const cookie = changed.headers.get('set-cookie')!.split(';')[0];
  const result = await f.app.request('/api/admin/auth/sessions', { headers: { Cookie: cookie } });
  const current = (await result.json()).sessions; expect(current).toHaveLength(1); expect(current[0].current).toBe(true);
  const revoked = await f.app.request(`/api/admin/auth/sessions/${current[0].hash}`, { method: 'DELETE', headers: { Cookie: cookie, 'X-CSRF-Token': auth.csrfToken, Origin: f.config.publicBaseUrl } });
  expect(revoked.status).toBe(200); expect(revoked.headers.get('set-cookie')).toContain('Max-Age=0');
});
it('heartbeat is isolated, bounded to its document, expires, and uses no persistence; rebuild is Admin+', async () => {
  const f = await fixture();
  const { doc } = await (await f.req('/docs/events', 'POST', { draft: { title: 'Presence event', date: '2030-06-01' } })).json();
  const writer = await (await f.req('/users', 'POST', { username: 'PresenceWriter', role: 'Contributor' })).json();
  const before = (await f.store.queryAudit({ limit: 100 })).items.length;
  const first = await f.req(`/docs/events/${doc.id}/presence`, 'POST'); expect((await first.json()).others).toEqual([]);
  await f.login('PresenceWriter', writer.temporaryPassword);
  const presence = await (await f.req(`/docs/events/${doc.id}/presence`, 'POST')).json();
  expect(presence.others).toEqual([{ id: (await f.store.getUserByUsername('Phil'))!.id, name: 'Phil' }]);
  expect(JSON.stringify(presence)).not.toMatch(/hash|csrf|session/);
  expect((await f.store.queryAudit({ limit: 100 })).items.length).toBe(before + 1); // login only
  const secondInstance = createAdminApp(() => f.store, { config: f.config, now: () => new Date('2030-01-01T12:00:00Z') });
  const isolated = await secondInstance.request(`/api/admin/docs/events/${doc.id}/presence`, { method: 'POST', headers: { Cookie: f.getCookie(), 'X-CSRF-Token': (await (await f.req('/auth/me')).json()).csrfToken } });
  expect((await isolated.json()).others).toEqual([]);
  f.clock('2030-01-01T12:01:16Z'); expect((await (await f.req(`/docs/events/${doc.id}/presence`, 'POST')).json()).others).toEqual([]);
  await f.login();
  const editor = await (await f.req('/users', 'POST', { username: 'Rebuilder', role: 'Editor' })).json();
  await f.login('Rebuilder', editor.temporaryPassword); expect((await f.req('/rebuild', 'POST')).status).toBe(403);
  await f.login(); expect((await f.req('/rebuild', 'POST')).status).toBe(200);
  expect((await f.store.listPublishes(1))[0].kind).toBe('rebuild');
  expect((await f.store.queryAudit({ limit: 100 })).items.some(a => a.action === 'content.rebuild')).toBe(true);
});

