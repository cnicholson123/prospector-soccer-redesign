import { afterEach, expect, it } from 'vitest';
import { rm } from 'node:fs/promises';
import { adminFixture, createUserWithPassword } from '../helpers/admin.js';
import { createRenderHandler } from '../../server/render/handler.js';
import type { Doc, Revision, AuditEntry } from '../../shared/types.js';
import type { SiteComparison } from '../../shared/history.js';
import { generatedPassword } from '../helpers/password.js';
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });
const item = (doc: Doc) => ({ collection: doc.collection, id: doc.id, expectedVersion: doc.version });
it('checkpoints two titles, restores and publishes forward, and exports the complete filtered audit across pages', async () => {
  const f = await adminFixture(true); roots.push(f.root); await f.login();
  let doc = (await f.store.getDoc('home', 'home'))!;
  const original = structuredClone(doc.draft) as { hero: { title: string } };
  for (let i = 1; i <= 2; i++) {
    f.clock(`2030-01-01T12:0${i}:00Z`);
    const draft = structuredClone(original); draft.hero.title = `History title ${i}`;
    const response = await f.req('/docs/home/home', 'PUT', { baseVersion: doc.version, draft, checkpoint: true, summary: `Title ${i}` });
    expect(response.status).toBe(200); doc = (await response.json()).doc;
  }
  const history = (await (await f.req('/revisions/home/home')).json()).revisions as Revision[];
  const first = history.find(rev => rev.summary === 'Title 1')!;
  expect(history.filter(rev => rev.summary?.startsWith('Title '))).toHaveLength(2);
  expect(history.filter(rev => rev.summary?.startsWith('Title ')).every(rev => rev.sealedAt)).toBe(true);
  const detail = await (await f.req(`/revisions/${history[0].id}?docId=home`)).json();
  expect(detail.diff).toContainEqual(expect.objectContaining({ path: 'hero.title', words: expect.any(Array) }));
  f.clock('2030-01-01T12:03:00Z'); expect((await f.req('/publish', 'POST', { items: [item(doc)] })).status).toBe(200);
  doc = (await f.store.getDoc('home', 'home'))!;
  f.clock('2030-01-01T12:04:00Z');
  const restored = await f.req(`/revisions/${first.id}/restore?docId=home`, 'POST', { baseVersion: doc.version, publish: true });
  expect(restored.status).toBe(200); expect((await restored.json()).published).toBe(true);
  const render = createRenderHandler(f.store, f.config);
  const html = await (await render(new Request('http://localhost:3000/'))).text();
  expect(html).toContain('History title 1'); expect(html).not.toContain('History title 2');
  expect((await f.store.getRevision('home', first.id))).toEqual(first);
  const q = 'collection=home&actionGroup=content&from=2030-01-01T12:01:00Z&to=2030-01-01T12:05:00Z';
  const page1 = await (await f.req(`/audit?${q}&limit=2`)).json();
  const page2 = await (await f.req(`/audit?${q}&limit=2&cursor=${page1.cursor}`)).json();
  expect(page1.items.map((row: AuditEntry) => row.action)).toEqual(['content.publish', 'content.restored']);
  expect(page2.items[0].action).toBe('content.publish');
  const exported = await f.req(`/audit/export?format=csv&${q}&limit=1`);
  const csv = await exported.text(); expect(exported.headers.get('content-disposition')).toContain('audit.csv');
  expect(csv.match(/content.checkpoint/g)).toHaveLength(2); expect(csv).toContain('content.restored'); expect(csv).not.toContain('auth.login');
  const login = await (await f.req('/audit?action=auth.login')).json(); expect(login.items[0].at < page2.items[0].at).toBe(true);
  const global = await (await f.req(`/revisions?collection=home&author=${first.authorId}&limit=2`)).json();
  expect(global.items).toHaveLength(2); expect(global.cursor).toBeTruthy();
  const next = await (await f.req(`/revisions?collection=home&author=${first.authorId}&limit=2&cursor=${global.cursor}`)).json();
  expect(next.items.every((rev: Revision) => !global.items.some((old: Revision) => old.id === rev.id))).toBe(true);
  expect((await f.req('/revisions?collection=invalid')).status).toBe(422);
  expect((await f.req('/audit?from=2030-02-01&to=2030-01-01')).status).toBe(422);
}, 15000);
it('previews every overwritten draft, live change, list order, later document and cancelled schedule; rejects stale confirmation', async () => {
  const f = await adminFixture(true); roots.push(f.root); await f.login();
  const original = (await f.store.getDoc('home', 'home'))!;
  const draft = structuredClone(original.draft) as { hero: { title: string }; programs: unknown[] }; draft.hero.title = 'Unpublished title'; draft.programs.reverse();
  let doc = (await (await f.req('/docs/home/home', 'PUT', { baseVersion: original.version, draft })).json()).doc as Doc;
  expect((await f.req('/schedule', 'POST', { items: [item(doc)], at: '2030-02-01T12:00:00Z' })).status).toBe(200);
  const created = (await (await f.req('/docs/events', 'POST', { draft: { title: 'Later event', date: '2030-06-01' } })).json()).doc as Doc;
  expect((await f.req('/publish', 'POST', { items: [item(created)] })).status).toBe(200);
  const comparison = (await (await f.req('/publishes/1?diff=1')).json()) as SiteComparison;
  const home = comparison.changes.find(c => c.id === 'home')!;
  expect(home.draftDiff).toContainEqual(expect.objectContaining({ path: 'hero.title', before: 'Unpublished title' }));
  expect(home.draftDiff.some(d => d.kind === 'moved')).toBe(true); expect(home.effects).toContain('Cancel scheduled publication');
  expect(comparison.changes.find(c => c.id === created.id)?.effects).toContain('Remove from live site; keep draft');
  expect(comparison.changes).toHaveLength((await f.store.capturePublication()).docs.length);
  doc = (await f.store.getDoc('home', 'home'))!;
  await f.req('/docs/home/home', 'PUT', { baseVersion: doc.version, draft: original.draft });
  const snapshot = await f.store.getSnapshot();
  expect((await f.req('/publishes/1/restore', 'POST', { token: comparison.token })).status).toBe(409);
  expect(await f.store.getSnapshot()).toEqual(snapshot);
  const fresh = (await (await f.req('/publishes/1?diff=1')).json()) as SiteComparison;
  const result = await f.req('/publishes/1/restore', 'POST', { token: fresh.token, summary: 'Reviewed complete restore' });
  expect(result.status).toBe(200);
  const current = (await f.store.getSnapshot())!;
  expect(current.siteVersion).toBeGreaterThan(1); expect(current.scheduled).toHaveLength(0);
  expect(current.docs.events?.some(d => d.id === created.id)).toBe(false);
  expect((await f.store.getDoc('events', created.id))?.draft).toEqual(created.draft);
}, 15000);
it('keeps history readable while enforcing audit and site restore roles', async () => {
  const f = await adminFixture(true); roots.push(f.root); await f.login();
  const password = generatedPassword();
  await createUserWithPassword(f, { username: 'Viewer', displayName: 'Viewer', role: 'Viewer', password });
  await f.login('Viewer', password);
  expect((await f.req('/revisions?limit=1')).status).toBe(200);
  const actors = await (await f.req('/audit/actors')).json();
  expect(Object.keys(actors.actors[0]).sort()).toEqual(['id', 'name']);
  expect((await f.req('/audit')).status).toBe(403); expect((await f.req('/audit/export')).status).toBe(403);
  expect((await f.req('/publishes/1/restore', 'POST', {})).status).toBe(403);
}, 15000);
